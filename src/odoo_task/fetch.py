"""Fetch one Odoo task and write it as a Markdown folder. Read-only."""

from __future__ import annotations

import re
from collections.abc import Sequence
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path
from typing import Any

from odoo_task.client import OdooClient, OdooError
from odoo_task.html_text import html_to_markdown
from odoo_task.images import localize_images
from odoo_task.taskref import task_folder_name

TASK_MODEL = "project.task"
TASK_FILE = "task.md"
PROMPT_FILE = "prompt.md"
MAX_ATTACHMENT_BYTES = 25 * 1024 * 1024
DEFAULT_LIST_LIMIT = 30
MAX_LIST_LIMIT = 200

# What a task shows by default. Fields that do not exist in this Odoo version or edition are skipped.
DEFAULT_FIELDS = ("name", "project_id", "stage_id", "user_ids", "tag_ids", "partner_id", "date_deadline", "description")

DEFAULT_PROMPT = """# Task #{task_id}: {title}

> Generated by odoo-task on {date}. Paste this file into your coding assistant.

## Your job

Implement the task described below. Work step by step, explain each change, and check the result against what the
task asks for before you say it is done. Ask when something is unclear instead of guessing.

## Task

{task_content}

## Answer format

For each requirement: what you changed (file and function), how to verify it by hand, and any open question.
"""


@dataclass
class ExtraField:
    name: str
    title: str | None = None

    @classmethod
    def parse(cls, text: str) -> ExtraField:
        name, _, title = text.partition(":")
        name = name.strip()
        if not name.replace("_", "").isalnum():
            raise ValueError(f"Not a valid field name: '{name}'")
        return cls(name, title.strip() or None)


@dataclass
class TaskSummary:
    """One line of the list of tasks."""

    id: int
    title: str
    project: str = ""
    stage: str = ""
    deadline: str = ""


@dataclass
class FetchResult:
    task_id: int
    title: str
    directory: Path
    markdown: Path
    images: list[str] = field(default_factory=list)
    attachments: list[str] = field(default_factory=list)
    skipped_fields: list[str] = field(default_factory=list)
    prompt: Path | None = None  # set when prompt.md was written


def _human_size(size: int) -> str:
    if size < 1024:
        return f"{size} B"
    if size < 1024 * 1024:
        return f"{size // 1024} KB"
    return f"{size / (1024 * 1024):.1f} MB"


def _label(value: Any) -> str:
    """A readable text for a value returned by Odoo."""
    if value is False or value is None:
        return ""
    if isinstance(value, (list, tuple)) and len(value) == 2 and isinstance(value[0], int) and isinstance(value[1], str):
        return value[1]
    return str(value)


class TaskFetcher:
    def __init__(self, client: OdooClient) -> None:
        self.client = client
        self._fields: dict[str, dict[str, Any]] | None = None

    # Schema --------------------------------------------------------------------------------------------------------

    def fields(self) -> dict[str, dict[str, Any]]:
        if self._fields is None:
            self._fields = self.client.fields_get(TASK_MODEL, ["string", "type", "relation", "selection", "searchable"])
        return self._fields

    # Which task ----------------------------------------------------------------------------------------------------

    def closed_domain(self) -> list[Any]:
        """A domain that keeps only the open tasks, with what this Odoo offers; empty when nothing can tell."""
        schema = self.fields()
        state = schema.get("state")
        if state and state.get("type") == "selection" and state.get("searchable", True):
            closed = [k for k, _label in state.get("selection") or [] if "done" in k.lower() or "cancel" in k.lower()]
            if closed:
                return [("state", "not in", closed)]
        if "is_closed" in schema and schema["is_closed"].get("searchable", True):
            return [("is_closed", "=", False)]
        return []

    def open_domain(self, closed_stages: Sequence[str] = ()) -> list[Any]:
        """What "open" means: Odoo's own rule (`state`), and also not in a folded stage, and not in a stage the user
        calls closed. A task with no stage is never hidden by the stage rules."""
        domain = self.closed_domain()
        if "stage_id" in self.fields():
            domain += ["|", ("stage_id", "=", False), ("stage_id.fold", "=", False)]
            names = [name.strip() for name in closed_stages if name.strip()]
            if names:
                domain += ["|", ("stage_id", "=", False), ("stage_id.name", "not in", names)]
        return domain

    def my_tasks(
        self, limit: int = DEFAULT_LIST_LIMIT, include_closed: bool = False, closed_stages: Sequence[str] = ()
    ) -> list[TaskSummary]:
        """The tasks assigned to the logged-in user, newest first. Closed ones only on request."""
        if self.client.uid is None:
            self.client.connect()
        schema = self.fields()
        domain: list[Any] = [("user_ids", "in", [self.client.uid])]
        if not include_closed:
            domain += self.open_domain(closed_stages)
        wanted = [f for f in ("name", "project_id", "stage_id", "date_deadline") if f in schema]
        rows = self.client.search_read(TASK_MODEL, domain, wanted, order="id desc", limit=max(1, limit))
        return [
            TaskSummary(
                id=int(r["id"]),
                title=str(r.get("name") or f"Task {r['id']}"),
                project=_label(r.get("project_id")),
                stage=_label(r.get("stage_id")),
                deadline=str(r.get("date_deadline") or ""),
            )
            for r in rows
        ]

    def newest_assigned_task_id(self, closed_stages: Sequence[str] = ()) -> int | None:
        """The newest open task assigned to the user."""
        tasks = self.my_tasks(limit=1, closed_stages=closed_stages)
        return tasks[0].id if tasks else None

    # Fetch ---------------------------------------------------------------------------------------------------------

    def _names(self, relation: str, ids: Sequence[int]) -> list[str]:
        if not ids:
            return []
        rows = self.client.read(relation, list(ids), ["display_name"])
        return [str(r.get("display_name", r["id"])) for r in rows]

    def _read_attachment(self, att_id: int) -> tuple[str, str] | None:
        try:
            rows = self.client.read("ir.attachment", [att_id], ["datas", "mimetype"])
        except OdooError:
            return None
        if rows and rows[0].get("datas"):
            return rows[0]["datas"], rows[0].get("mimetype") or ""
        return None

    def fetch(
        self,
        task_id: int,
        out_root: Path,
        extra_fields: Sequence[ExtraField] = (),
        messages: int = 0,
        attachments: bool = False,
        base_url: str | None = None,
    ) -> FetchResult:
        schema = self.fields()
        wanted = [f for f in DEFAULT_FIELDS if f in schema]
        skipped = [e.name for e in extra_fields if e.name not in schema]
        usable_extra = [e for e in extra_fields if e.name in schema]
        read_fields = list(dict.fromkeys(wanted + [e.name for e in usable_extra]))

        rows = self.client.read(TASK_MODEL, [task_id], read_fields)
        if not rows:
            raise OdooError(f"Task {task_id} not found (or you may not read it).")
        task = rows[0]
        title = str(task.get("name") or f"Task {task_id}")

        folder = out_root / task_folder_name(task_id, title)
        folder.mkdir(parents=True, exist_ok=True)
        folder.chmod(0o700)  # a task can hold customer data: only its owner reads it

        meta: list[tuple[str, str]] = []
        for fname, label in (("project_id", "Project"), ("stage_id", "Stage"), ("partner_id", "Customer")):
            if fname in task and task[fname]:
                meta.append((label, _label(task[fname])))
        for fname, label in (("user_ids", "Assignees"), ("tag_ids", "Tags")):
            if task.get(fname):
                meta.append((label, ", ".join(self._names(schema[fname]["relation"], task[fname]))))
        if task.get("date_deadline"):
            meta.append(("Deadline", str(task["date_deadline"])))
        if base_url:
            meta.append(("Link", f"{base_url.rstrip('/')}/web#id={task_id}&model={TASK_MODEL}&view_type=form"))

        description_html, images = localize_images(str(task.get("description") or ""), folder, self._read_attachment)
        sections: list[tuple[str, str]] = [
            ("Description", html_to_markdown(description_html, keep_images=True, base_url=self.client.url))
        ]
        for extra in usable_extra:
            value = task.get(extra.name)
            ftype = schema[extra.name].get("type")
            text = (
                html_to_markdown(str(value), keep_images=False, base_url=self.client.url)
                if ftype == "html"
                else _label(value)
            )
            sections.append((extra.title or str(schema[extra.name].get("string") or extra.name), text))

        # An attachment already shown in the description is not downloaded or shown a second time.
        known = {int(m.group(1)): n for n in images if (m := re.match(r"img_att_(\d+)\.", n))}
        attached = self._attachments(task_id, folder, download=attachments, known=known)
        chatter = self._messages(task_id, messages) if messages else []

        markdown = render_markdown(title, meta, sections, attached, chatter)
        path = folder / TASK_FILE
        path.write_text(markdown, encoding="utf-8")
        return FetchResult(task_id, title, folder, path, images, [a[0] for a in attached], skipped)

    # Attachments and messages

    def _attachments(
        self, task_id: int, folder: Path, download: bool, known: dict[int, str] | None = None
    ) -> list[tuple[str, str]]:
        rows = self.client.search_read(
            "ir.attachment",
            [("res_model", "=", TASK_MODEL), ("res_id", "=", task_id)],
            ["name", "mimetype", "file_size"],
            order="id",
            limit=100,
        )
        out: list[tuple[str, str]] = []
        for row in rows:
            name = Path(str(row.get("name") or f"attachment_{row['id']}")).name or f"attachment_{row['id']}"
            note = f"{row.get('mimetype') or 'file'}, {_human_size(int(row.get('file_size') or 0))}"
            if known and int(row["id"]) in known:
                out.append((known[int(row["id"])], f"{note}, shown in the description"))
                continue
            if download and int(row.get("file_size") or 0) <= MAX_ATTACHMENT_BYTES:
                got = self._read_attachment(int(row["id"]))
                if got:
                    import base64

                    target = folder / "attachments"
                    target.mkdir(exist_ok=True)
                    target.chmod(0o700)
                    safe = f"{row['id']}_{name}"
                    (target / safe).write_bytes(base64.b64decode(got[0]))
                    name, note = f"attachments/{safe}", note
            out.append((name, note))
        return out

    def _messages(self, task_id: int, limit: int) -> list[dict[str, str]]:
        rows = self.client.search_read(
            "mail.message",
            [("model", "=", TASK_MODEL), ("res_id", "=", task_id), ("message_type", "in", ["comment", "email"])],
            ["date", "author_id", "body"],
            order="id desc",
            limit=limit,
        )
        return [
            {
                "date": str(r.get("date") or ""),
                "author": _label(r.get("author_id")),
                "body": html_to_markdown(r.get("body"), keep_images=False, base_url=self.client.url),
            }
            for r in reversed(rows)
        ]


def render_markdown(
    title: str,
    meta: Sequence[tuple[str, str]],
    sections: Sequence[tuple[str, str]],
    attachments: Sequence[tuple[str, str]] = (),
    messages: Sequence[dict[str, str]] = (),
) -> str:
    lines = [f"# {title}", ""]
    if meta:
        lines += [f"- **{k}:** {v}" for k, v in meta] + [""]
    for heading, body in sections:
        lines += [f"## {heading}", "", body or "_(empty)_", ""]
    if attachments:
        lines += ["## Attachments", ""]
        for name, note in attachments:
            lines.append(f"- {name} ({note})")
            if name.startswith("attachments/") and note.startswith("image/"):
                lines += ["", f"  ![{name.rsplit('/', 1)[-1]}]({name})", ""]
        lines.append("")
    if messages:
        lines += ["## Latest messages", ""]
        for m in messages:
            lines += [f"**{m['author'] or 'Someone'}**, {m['date']}", "", m["body"] or "_(empty)_", ""]
    return "\n".join(lines).rstrip() + "\n"


def render_prompt(task_id: int, title: str, task_markdown: str, template: str | None = None) -> str:
    """Fill a prompt template in one pass, so a task text containing a placeholder cannot be expanded again."""
    text = template if template is not None else DEFAULT_PROMPT
    values = {
        "{task_id}": str(task_id),
        "{title}": title,
        "{date}": datetime.now().strftime("%Y-%m-%d %H:%M"),
        "{task_content}": task_markdown.strip(),
    }
    return re.sub("|".join(re.escape(k) for k in values), lambda m: values[m.group(0)], text)
